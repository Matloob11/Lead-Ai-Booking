"""Render English PDF for one agent day."""

from __future__ import annotations

from io import BytesIO
from pathlib import Path

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

from ..bitrix.metrics import AgentDaySnapshot


def build_pdf_bytes(snapshot: AgentDaySnapshot, ai_summary: str) -> bytes:
    buf = BytesIO()
    doc = SimpleDocTemplate(
        buf,
        pagesize=A4,
        leftMargin=18 * mm,
        rightMargin=18 * mm,
        topMargin=16 * mm,
        bottomMargin=16 * mm,
        title=f"Agent report — {snapshot.agent_name} — {snapshot.day}",
    )
    styles = getSampleStyleSheet()
    title = ParagraphStyle(
        "TitleAR",
        parent=styles["Heading1"],
        fontSize=16,
        spaceAfter=6,
        textColor=colors.HexColor("#0f172a"),
    )
    sub = ParagraphStyle(
        "SubAR",
        parent=styles["Normal"],
        fontSize=10,
        textColor=colors.HexColor("#64748b"),
        spaceAfter=12,
    )
    body = ParagraphStyle(
        "BodyAR",
        parent=styles["Normal"],
        fontSize=11,
        leading=15,
        spaceAfter=8,
    )
    h2 = ParagraphStyle(
        "H2AR",
        parent=styles["Heading2"],
        fontSize=12,
        spaceBefore=10,
        spaceAfter=6,
        textColor=colors.HexColor("#0f9f5c"),
    )

    story = [
        Paragraph("A7 Agent Daily Report", title),
        Paragraph(
            f"{_esc(snapshot.agent_name)} · {snapshot.day} · {snapshot.timezone}",
            sub,
        ),
        Paragraph("Summary", h2),
        Paragraph(_esc(ai_summary or "No summary."), body),
        Paragraph("Activity", h2),
    ]

    rows = [
        ["Metric", "Value"],
        ["Check-in", "Yes" if snapshot.timeman.checked_in else "No / unknown"],
        ["Timeman status", snapshot.timeman.status or "—"],
        ["Open leads (classic)", str(snapshot.leads.classic_open)],
        ["Open Owner Data", str(snapshot.leads.owner_data_open)],
        ["Total open book", str(snapshot.leads.total_open)],
        ["New classic leads today", str(snapshot.leads.new_classic_today)],
        ["New Owner Data today", str(snapshot.leads.new_owner_data_today)],
        ["Calls today", str(snapshot.calls.count)],
        ["Talk time (minutes)", str(snapshot.calls.talk_minutes)],
        ["Tasks open", str(snapshot.tasks.open_count)],
        ["Tasks completed today", str(snapshot.tasks.completed_today)],
    ]
    table = Table(rows, colWidths=[90 * mm, 70 * mm])
    table.setStyle(
        TableStyle(
            [
                ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#0f172a")),
                ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
                ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
                ("FONTSIZE", (0, 0), (-1, -1), 10),
                ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#f8fafc")]),
                ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#e2e8f0")),
                ("LEFTPADDING", (0, 0), (-1, -1), 8),
                ("RIGHTPADDING", (0, 0), (-1, -1), 8),
                ("TOPPADDING", (0, 0), (-1, -1), 6),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
            ]
        )
    )
    story.append(table)

    if snapshot.errors:
        story.append(Spacer(1, 8))
        story.append(Paragraph("Collection notes", h2))
        for err in snapshot.errors:
            story.append(Paragraph(f"• {_esc(err)}", body))

    story.append(Spacer(1, 16))
    story.append(
        Paragraph(
            "Generated by A7 Agent Reports. Numbers come from Bitrix; narrative is AI-assisted.",
            sub,
        )
    )
    doc.build(story)
    return buf.getvalue()


def write_pdf(snapshot: AgentDaySnapshot, ai_summary: str, path: Path) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(build_pdf_bytes(snapshot, ai_summary))
    return path


def _esc(text: str) -> str:
    return (
        (text or "")
        .replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
    )
